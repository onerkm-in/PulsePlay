// In-app floating panel: a fixed-position draggable overlay. Drag tracks
// clientX/Y delta from the mousedown anchor to avoid jitter from event
// batching; CSS `resize: both` gives corner-resize without JS. Not modal,
// so the BI canvas behind it remains interactive.
function FloatingPanel(props: {
    pos: { x: number; y: number };
    onPosChange: (pos: { x: number; y: number }) => void;
    onDock: () => void;
    title: string;
    children: React.ReactNode;
}): React.ReactElement {
    // Store drag-start state in a ref (not React state) so mousemove
    // handlers always read the value at capture time without stale closures.
    const dragAnchor = useRef<{
        startClientX: number; startClientY: number;
        startPosX: number; startPosY: number;
    } | null>(null);

    const onDragHandleMouseDown = useCallback((e: React.MouseEvent<HTMLDivElement>) => {
        if (e.button !== 0) return;
        e.preventDefault();
        dragAnchor.current = {
            startClientX: e.clientX,
            startClientY: e.clientY,
            startPosX: props.pos.x,
            startPosY: props.pos.y,
        };
        const onMove = (ev: MouseEvent) => {
            const a = dragAnchor.current;
            if (!a) return;
            // Clamp drag bounds to the viewport so the header buttons (Dock,
            // Close) always remain reachable. Use the panel's live bounding
            // rect for width to handle the resize:both case.
            const vw = typeof window !== "undefined" ? window.innerWidth : 1200;
            const vh = typeof window !== "undefined" ? window.innerHeight : 800;
            const rect = (ev.target as Element)?.closest?.('[role="complementary"]')?.getBoundingClientRect();
            const w = rect?.width ?? 520;
            const h = rect?.height ?? 480;
            const MARGIN = 16;
            const nextX = a.startPosX + ev.clientX - a.startClientX;
            const nextY = a.startPosY + ev.clientY - a.startClientY;
            props.onPosChange({
                x: Math.min(Math.max(MARGIN, nextX), Math.max(MARGIN, vw - w - MARGIN)),
                y: Math.min(Math.max(MARGIN, nextY), Math.max(MARGIN, vh - h - MARGIN)),
            });
        };
        const onUp = () => {
            dragAnchor.current = null;
            document.removeEventListener("mousemove", onMove);
            document.removeEventListener("mouseup", onUp);
        };
        document.addEventListener("mousemove", onMove);
        document.addEventListener("mouseup", onUp);
    }, [props]);

    // Derive width from the viewport so the panel never exceeds the screen;
    // a hardcoded 520 px width put the Dock button offscreen at 390 px.
    const viewportW = typeof window !== "undefined" ? window.innerWidth : 1200;
    const computedWidth = Math.min(520, Math.max(300, viewportW - 32));

    return (
        <div
            role="complementary"
            aria-label={props.title}
            className="pp-float-panel"
            style={{
                position: "fixed",
                left: props.pos.x,
                top: props.pos.y,
                width: computedWidth,
                height: "80vh",
                maxWidth: "calc(100vw - 32px)",
                minWidth: 280,
                minHeight: 220,
                zIndex: 1200,
                display: "flex",
                flexDirection: "column",
                outline: "none",
                overflow: "hidden",
                resize: "both",
            }}
        >
            {/* Drag handle strip, kept minimal: title + dock button. */}
            <div className="pp-float-panel__handle" onMouseDown={onDragHandleMouseDown}>
                <span aria-hidden="true" className="pp-float-panel__dots">⠿</span>
                <span className="pp-float-panel__title">{props.title}</span>
                <button
                    type="button"
                    onClick={props.onDock}
                    title="Dock back to split layout"
                    aria-label="Dock panel back to split layout"
                    className="pp-float-panel__dock"
                >
                    Dock ↙
                </button>
            </div>
            <div style={{ flex: "1 1 auto", minHeight: 0, overflow: "hidden" }}>
                {props.children}
            </div>
        </div>
    );
}

function LivePaneMirror(props: {
    sourceRef: React.RefObject<HTMLElement | null>;
    label: string;
}): React.ReactElement {
    const mirrorRef = useRef<HTMLDivElement | null>(null);
    const [hasSource, setHasSource] = useState(false);

    useEffect(() => {
        let observer: MutationObserver | null = null;
        let raf = 0;
        let retryTimer = 0;
        let sourceWithListeners: HTMLElement | null = null;

        const copyFormState = (source: HTMLElement, clone: HTMLElement) => {
            const sourceControls = Array.from(source.querySelectorAll<HTMLInputElement | HTMLTextAreaElement | HTMLSelectElement>("input, textarea, select"));
            const cloneControls = Array.from(clone.querySelectorAll<HTMLInputElement | HTMLTextAreaElement | HTMLSelectElement>("input, textarea, select"));
            sourceControls.forEach((sourceControl, index) => {
                const cloneControl = cloneControls[index];
                if (!cloneControl) return;
                if (sourceControl instanceof HTMLInputElement && cloneControl instanceof HTMLInputElement) {
                    cloneControl.checked = sourceControl.checked;
                    cloneControl.value = sourceControl.value;
                } else if (sourceControl instanceof HTMLTextAreaElement && cloneControl instanceof HTMLTextAreaElement) {
                    cloneControl.value = sourceControl.value;
                    cloneControl.textContent = sourceControl.value;
                } else if (sourceControl instanceof HTMLSelectElement && cloneControl instanceof HTMLSelectElement) {
                    cloneControl.selectedIndex = sourceControl.selectedIndex;
                }
            });
        };

        const stripDuplicateIdsAndFocus = (clone: HTMLElement) => {
            clone.querySelectorAll<HTMLElement>("[id]").forEach(el => el.removeAttribute("id"));
            clone.querySelectorAll<HTMLElement>("a, button, input, textarea, select, [tabindex]").forEach(el => {
                el.setAttribute("tabindex", "-1");
                el.setAttribute("aria-hidden", "true");
            });
            clone.style.width = "100%";
            clone.style.height = "100%";
            clone.style.minHeight = "100%";
            clone.style.pointerEvents = "none";
        };

        const sync = () => {
            const source = props.sourceRef.current;
            const mirror = mirrorRef.current;
            if (!mirror) return;
            if (!source) {
                setHasSource(false);
                mirror.textContent = "";
                return;
            }
            const clone = source.cloneNode(true) as HTMLElement;
            copyFormState(source, clone);
            stripDuplicateIdsAndFocus(clone);
            mirror.textContent = "";
            mirror.appendChild(clone);
            setHasSource(true);
        };

        const scheduleSync = () => {
            if (raf) cancelAnimationFrame(raf);
            raf = requestAnimationFrame(sync);
        };

        const connect = () => {
            const source = props.sourceRef.current;
            if (!source) {
                sync();
                retryTimer = window.setTimeout(connect, 50);
                return;
            }
            sourceWithListeners = source;
            sync();
            if (typeof MutationObserver !== "undefined") {
                observer = new MutationObserver(scheduleSync);
                observer.observe(source, {
                    attributes: true,
                    characterData: true,
                    childList: true,
                    subtree: true,
                });
            }
            source.addEventListener("input", scheduleSync, true);
            source.addEventListener("change", scheduleSync, true);
        };

        connect();

        return () => {
            observer?.disconnect();
            if (raf) cancelAnimationFrame(raf);
            if (retryTimer) window.clearTimeout(retryTimer);
            sourceWithListeners?.removeEventListener("input", scheduleSync, true);
            sourceWithListeners?.removeEventListener("change", scheduleSync, true);
        };
    }, [props.sourceRef]);

    return (
        <div
            data-testid="pp-live-pane-mirror"
            role="img"
            aria-label={props.label}
            style={{
                width: "100%",
                height: "100%",
                minHeight: 0,
                overflow: "auto",
                background: "var(--pp-surface, #fff)",
                position: "relative",
            }}
        >
            {!hasSource && (
                <div
                    style={{
                        position: "absolute",
                        inset: 0,
                        display: "grid",
                        placeItems: "center",
                        padding: 16,
                        color: "var(--pp-text-muted, #64748b)",
                        fontSize: 12,
                        textAlign: "center",
                    }}
                >
                    Preparing live mirror...
                </div>
            )}
            <div
                ref={mirrorRef}
                aria-hidden="true"
                style={{
                    width: "100%",
                    minHeight: "100%",
                    pointerEvents: "none",
                }}
            />
        </div>
    );
}

// Resizable split layout. With both panels visible, renders a `Group` with a
// draggable divider; with one panel, renders it full-canvas without the group.
// `useDefaultLayout` persists the split ratio per orientation in localStorage.
function SplitLayout(props: {
    aiVisible: boolean;
    biVisible: boolean;
    layoutMode: LayoutMode;
    focusedPane: ViewportFocus;
    aiContent: React.ReactNode;
    biContent: React.ReactNode;
    emptyContent: React.ReactNode;
    /** Mix mode. When true and exactly one pane is visible, render both panes
     *  (toggle visibility instead of unmounting) so switching surfaces never
     *  reloads loaded content. Left false for aiOnly/biOnly where the off
     *  pane is truly disabled. */
    keepHiddenPaneMounted?: boolean;
}): React.ReactElement {
    const { aiVisible, biVisible, layoutMode, focusedPane, aiContent, biContent, emptyContent, keepHiddenPaneMounted } = props;

    const orientation: "horizontal" | "vertical" =
        layoutMode === "ai-top" || layoutMode === "ai-bottom" ? "vertical" : "horizontal";
    // Persist the split ratio per orientation. Row and column layouts get
    // independent saved sizes so each feels natural.
    const { defaultLayout, onLayoutChanged } = useDefaultLayout({
        id: `pulseplay:split:${orientation}`,
        storage: typeof window !== "undefined" ? window.localStorage : undefined,
    });

    // Stacked-frame renderer: both panes mounted, only the active one
    // visible. Shared by the focusedPane (maximize) and mix-mode (single-
    // surface-at-a-time) branches so neither unmounts the inactive pane.
    const stackedFrames = (activePane: ViewportPane) => {
        const frame = (pane: ViewportPane, content: React.ReactNode) => {
            const isActive = activePane === pane;
            return (
                <div
                    key={pane}
                    aria-hidden={isActive ? undefined : true}
                    style={{
                        position: "absolute",
                        inset: 0,
                        zIndex: isActive ? 2 : 1,
                        width: "100%",
                        height: "100%",
                        minWidth: 0,
                        minHeight: 0,
                        overflow: "hidden",
                        opacity: isActive ? 1 : 0,
                        pointerEvents: isActive ? "auto" : "none",
                        visibility: isActive ? "visible" : "hidden",
                    }}
                >
                    {content}
                </div>
            );
        };
        return (
            <div style={{ position: "relative", width: "100%", height: "100%", minWidth: 0, minHeight: 0 }}>
                {frame("ai", aiContent)}
                {frame("bi", biContent)}
            </div>
        );
    };

    if (focusedPane) {
        return stackedFrames(focusedPane);
    }

    // Mix mode: exactly one pane visible, but both are enabled. Keep both
    // mounted and toggle visibility so switches between AI and Dashboard
    // preserve loaded state. (aiVisible !== biVisible guards against the
    // both-on / both-off cases, which fall through to the split/empty layouts.)
    if (keepHiddenPaneMounted && aiVisible !== biVisible) {
        return stackedFrames(aiVisible ? "ai" : "bi");
    }

    if (!aiVisible && !biVisible) return <>{emptyContent}</>;
    if (aiVisible && !biVisible) return <>{aiContent}</>;
    if (!aiVisible && biVisible) return <>{biContent}</>;

    const aiFirst = layoutMode === "ai-left" || layoutMode === "ai-top";
    const aiDefaultSize = orientation === "horizontal" ? 35 : 40;
    const biDefaultSize = 100 - aiDefaultSize;

    const sepStyle: React.CSSProperties = orientation === "horizontal"
        ? { width: 6, background: "transparent", cursor: "col-resize", position: "relative", flexShrink: 0 }
        : { height: 6, background: "transparent", cursor: "row-resize", position: "relative", flexShrink: 0 };
    const sepInnerStyle: React.CSSProperties = orientation === "horizontal"
        ? { position: "absolute", left: 2, top: 0, width: 2, height: "100%", background: "rgba(0,0,0,0.08)" }
        : { position: "absolute", top: 2, left: 0, height: 2, width: "100%", background: "rgba(0,0,0,0.08)" };

    const aiPanel = (
        <Panel defaultSize={`${aiDefaultSize}%`} minSize="15%" id="ai">{aiContent}</Panel>
    );
    const biPanel = (
        <Panel defaultSize={`${biDefaultSize}%`} minSize="15%" id="bi">{biContent}</Panel>
    );
    const separator = (
        <Separator style={sepStyle}>
            <div style={sepInnerStyle} />
        </Separator>
    );

    return (
        <Group
            orientation={orientation}
            defaultLayout={defaultLayout}
            onLayoutChanged={onLayoutChanged}
            style={{ width: "100%", height: "100%" }}
        >
            {aiFirst ? aiPanel : biPanel}
            {separator}
            {aiFirst ? biPanel : aiPanel}
        </Group>
    );
}

